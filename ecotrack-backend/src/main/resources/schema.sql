-- 8. CHALLENGES TABLE
-- Admin-authored challenge definitions. NOTE: intentionally no stored
-- lifecycle status column. UPCOMING / ACTIVE / ENDED is always derived at
-- read time from cancelled + today's date vs. start_date/end_date.
-- This avoids a second source of truth that can drift out of sync with dates.
CREATE TABLE IF NOT EXISTS challenges (
    challenge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    category VARCHAR(100) NOT NULL,             -- e.g., 'TRANSPORTATION', 'ELECTRICITY'
    challenge_type VARCHAR(50) NOT NULL,        -- 'CARBON_REDUCTION' or 'ACTIVITY_BASED'
    tracking_type VARCHAR(50),                  -- 'COUNT', 'DISTANCE', 'DURATION', 'BOOLEAN' (activity challenges only)
    target_value DECIMAL NOT NULL,              -- % reduction for carbon challenges; raw amount for activity challenges
    unit VARCHAR(50),                           -- e.g., '%', 'km', 'trees', 'minutes'
    reward_xp INT DEFAULT 100,                  -- XP awarded on completion
    badge_image_url VARCHAR(255),               -- Path to badge (e.g., 'ch_1.avif')
    card_image_url VARCHAR(255),                -- Path to challenge card header image (e.g., 'ch_card_1.avif')
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_by BIGINT NOT NULL,                 -- Admin (users.id) who created this challenge
    cancelled BOOLEAN NOT NULL DEFAULT FALSE,   -- Soft-cancellation flag
    cancelled_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_challenge_created_by
        FOREIGN KEY (created_by) REFERENCES users(id),

    -- Challenge must be at least 7 days long
    CONSTRAINT chk_challenge_min_duration
        CHECK (end_date - start_date >= 7),

    -- Start date must be before end date
    CONSTRAINT chk_challenge_valid_dates
        CHECK (start_date < end_date),

    -- Target and XP cannot be negative
    CONSTRAINT chk_challenge_target_non_negative
        CHECK (target_value >= 0),

    CONSTRAINT chk_challenge_reward_xp_non_negative
        CHECK (reward_xp >= 0),

    -- Only supported challenge types are allowed
    CONSTRAINT chk_challenge_type
        CHECK (
            challenge_type IN (
                'CARBON_REDUCTION',
                'ACTIVITY_BASED'
            )
        ),

    -- Only supported tracking types are allowed
    CONSTRAINT chk_challenge_tracking_type
        CHECK (
            tracking_type IS NULL
            OR tracking_type IN (
                'COUNT',
                'DISTANCE',
                'DURATION',
                'BOOLEAN'
            )
        ),

    -- cancelled_at must match the cancellation flag
    CONSTRAINT chk_challenge_cancelled_timestamp
        CHECK (
            (cancelled = FALSE AND cancelled_at IS NULL)
            OR
            (cancelled = TRUE AND cancelled_at IS NOT NULL)
        )
);

CREATE INDEX IF NOT EXISTS idx_challenges_created_by
    ON challenges(created_by);


-- 9. USER CHALLENGES (PARTICIPATION & PROGRESS)
-- One row per user per joined challenge.
--
-- baseline_value / start_entry_id / effective_target are
-- carbon-reduction-only: calculated at join time and frozen so that
-- a user's target does not silently change during the challenge.
CREATE TABLE IF NOT EXISTS user_challenges (
    user_challenge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    challenge_id BIGINT NOT NULL,

    baseline_value DECIMAL,                     -- Carbon-only: scaled 30-day baseline, frozen at join
    start_entry_id BIGINT,                      -- Carbon-only: anchor into carbon_entries (same approach as Goal.startEntryId)
    effective_target DECIMAL,                   -- Carbon-only: final frozen kg ceiling for this user

    current_value DECIMAL DEFAULT 0,
    completion_percentage DECIMAL DEFAULT 0,

    status VARCHAR(30) NOT NULL DEFAULT 'JOINED',
    -- JOINED, IN_PROGRESS, COMPLETED, EXPIRED, CANCELLED
    -- No FAILED state: a user remains in the challenge until it ends;
    -- if the target is not achieved by the end, the participation becomes EXPIRED.

    joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,

    CONSTRAINT fk_user_challenge_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,

    CONSTRAINT fk_user_challenge_challenge
        FOREIGN KEY (challenge_id) REFERENCES challenges(challenge_id) ON DELETE CASCADE,

    CONSTRAINT uq_user_challenge
        UNIQUE (user_id, challenge_id),

    -- Progress values cannot be negative
    CONSTRAINT chk_user_challenge_current_value
        CHECK (current_value >= 0),

    -- Completion percentage must remain between 0 and 100
    CONSTRAINT chk_user_challenge_completion_percentage
        CHECK (
            completion_percentage >= 0
            AND completion_percentage <= 100
        ),

    -- Carbon baseline and effective target cannot be negative
    CONSTRAINT chk_user_challenge_baseline
        CHECK (
            baseline_value IS NULL
            OR baseline_value >= 0
        ),

    CONSTRAINT chk_user_challenge_effective_target
        CHECK (
            effective_target IS NULL
            OR effective_target >= 0
        ),

    -- Only supported participation states are allowed
    CONSTRAINT chk_user_challenge_status
        CHECK (
            status IN (
                'JOINED',
                'IN_PROGRESS',
                'COMPLETED',
                'EXPIRED',
                'CANCELLED'
            )
        ),

    -- A completed challenge participation must have a completion timestamp
    CONSTRAINT chk_user_challenge_completed_at
        CHECK (
            (status = 'COMPLETED' AND completed_at IS NOT NULL)
            OR
            (status <> 'COMPLETED')
        )
);

CREATE INDEX IF NOT EXISTS idx_user_challenges_user_id
    ON user_challenges(user_id);

CREATE INDEX IF NOT EXISTS idx_user_challenges_challenge_id
    ON user_challenges(challenge_id);

-- 10. TRIGGERS
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS '
BEGIN 
    NEW.updated_at = CURRENT_TIMESTAMP; 
    RETURN NEW; 
END;
' LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_challenges_updated_at ON challenges;
CREATE TRIGGER trg_challenges_updated_at BEFORE UPDATE ON challenges
FOR EACH ROW EXECUTE FUNCTION set_updated_at();