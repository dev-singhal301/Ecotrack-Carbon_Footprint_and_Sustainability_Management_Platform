/* ====================================================================
   ECOTRACK DATABASE SCHEMA (PostgreSQL)
   ==================================================================== */

-- 1. ROLES TABLE
CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

INSERT INTO roles (name)
VALUES
('ROLE_ADMIN'),
('ROLE_USER')
ON CONFLICT (name) DO NOTHING;


-- 2. USERS TABLE
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255),
    oauth_provider VARCHAR(30),
    oauth_id VARCHAR(255) UNIQUE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    reset_password_token VARCHAR(255) DEFAULT NULL,
    token_expiry_date TIMESTAMP DEFAULT NULL,
    user_level INT DEFAULT 1,
    user_rank VARCHAR(50) DEFAULT 'Eco Starter',
    current_xp INT DEFAULT 0,
    next_level_xp_target INT DEFAULT 50,
    reward_points INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_role
        FOREIGN KEY (role_id)
        REFERENCES roles(id)
);

-- Existing User Table Patches
ALTER TABLE users ADD COLUMN IF NOT EXISTS user_level INT DEFAULT 1;
ALTER TABLE users ADD COLUMN IF NOT EXISTS user_rank VARCHAR(50) DEFAULT 'Eco Starter';
ALTER TABLE users ADD COLUMN IF NOT EXISTS current_xp INT DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS next_level_xp_target INT DEFAULT 50;
ALTER TABLE users ADD COLUMN IF NOT EXISTS reward_points INT DEFAULT 0;


-- 3. EMISSION FACTORS TABLE
CREATE TABLE IF NOT EXISTS emission_factors (
    emission_factor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(100) NOT NULL UNIQUE,
    unit VARCHAR(50) NOT NULL,
    factor_value DECIMAL NOT NULL,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Seed data — standard factors per category
INSERT INTO emission_factors (category, unit, factor_value) VALUES
('TRANSPORTATION', 'km', 0.21),
('ELECTRICITY', 'kWh', 0.45),
('FOOD', 'kg', 2.5),
('WASTE', 'kg', 0.1),
('WATER', 'litres', 0.0003),
('FUEL', 'litres', 2.68)
ON CONFLICT (category) DO NOTHING;


-- 4. CARBON ENTRIES TABLE
CREATE TABLE IF NOT EXISTS carbon_entries (
    entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    emission_factor_id BIGINT NOT NULL,
    category VARCHAR(100) NOT NULL,
    amount DECIMAL NOT NULL,
    unit VARCHAR(50) NOT NULL,
    carbon_emission DECIMAL NOT NULL,
    activity_date DATE NOT NULL,
    
    CONSTRAINT fk_entry_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_entry_factor FOREIGN KEY (emission_factor_id) REFERENCES emission_factors(emission_factor_id)
);


-- 5. GOALS TABLE
CREATE TABLE IF NOT EXISTS goals (
    goal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    goal_name VARCHAR(150) NOT NULL,
    goal_type VARCHAR(50) NOT NULL,
    target_value DECIMAL NOT NULL,
    baseline_value DECIMAL DEFAULT 0,
    reward_points INT DEFAULT 0,
    xp_reward INT DEFAULT 100,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(30) DEFAULT 'ACTIVE',
    start_entry_id BIGINT DEFAULT 0,
    CONSTRAINT fk_goal_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_goals_user_id ON goals(user_id);

-- Existing Goals Table Patches (For Teammates with older schema instances)
ALTER TABLE goals ADD COLUMN IF NOT EXISTS baseline_value DECIMAL DEFAULT 0;
ALTER TABLE goals ADD COLUMN IF NOT EXISTS reward_points INT DEFAULT 0;
ALTER TABLE goals ADD COLUMN IF NOT EXISTS xp_reward INT DEFAULT 100;
ALTER TABLE goals ADD COLUMN IF NOT EXISTS start_entry_id BIGINT DEFAULT 0;


-- 6. GOAL PROGRESS TABLE
CREATE TABLE IF NOT EXISTS goal_progress (
    progress_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id BIGINT NOT NULL,
    current_value DECIMAL DEFAULT 0,
    completion_percentage DECIMAL DEFAULT 0,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_date DATE,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_progress_goal FOREIGN KEY (goal_id) REFERENCES goals(goal_id)
);

CREATE INDEX IF NOT EXISTS idx_goal_progress_goal_id ON goal_progress(goal_id);


-- 7. CARBON FOOTPRINT TABLE
CREATE TABLE IF NOT EXISTS carbon_footprint (
    footprint_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    period VARCHAR(50) NOT NULL,
    total_emission DECIMAL DEFAULT 0,
    electricity_emission DECIMAL DEFAULT 0,
    transportation_emission DECIMAL DEFAULT 0,
    fuel_emission DECIMAL DEFAULT 0,
    water_emission DECIMAL DEFAULT 0,
    waste_emission DECIMAL DEFAULT 0,
    food_emission DECIMAL DEFAULT 0,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_footprint_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_carbon_footprint_user_id ON carbon_footprint(user_id);


-- 8. TRIGGERS
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS '
BEGIN 
    NEW.updated_at = CURRENT_TIMESTAMP; 
    RETURN NEW; 
END;
' LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();