-- Milestone 2 — goals, goal_progress, carbon_footprint

CREATE TABLE IF NOT EXISTS goals (
    goal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    goal_name VARCHAR(150) NOT NULL,
    goal_type VARCHAR(50) NOT NULL,
    target_value DECIMAL NOT NULL,
    reward_points INT DEFAULT 0,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(30) DEFAULT 'ACTIVE',
    CONSTRAINT fk_goal_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_goals_user_id ON goals(user_id);

CREATE TABLE IF NOT EXISTS goal_progress (
    progress_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id BIGINT NOT NULL,
    current_value DECIMAL DEFAULT 0,
    completion_percentage DECIMAL DEFAULT 0,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_date DATE,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_progress_goal FOREIGN KEY (goal_id) REFERENCES goals(goal_id)
);
CREATE INDEX IF NOT EXISTS idx_goal_progress_goal_id ON goal_progress(goal_id);

CREATE TABLE IF NOT EXISTS carbon_footprint (
    footprint_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    period VARCHAR(50) NOT NULL,
    total_emission DECIMAL DEFAULT 0,
    electricity_emission DECIMAL DEFAULT 0,
    transportation_emission DECIMAL DEFAULT 0,
    fuel_emission DECIMAL DEFAULT 0,
    water_emission DECIMAL DEFAULT 0,
    waste_emission DECIMAL DEFAULT 0,
    food_emission DECIMAL DEFAULT 0,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_footprint_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_carbon_footprint_user_id ON carbon_footprint(user_id);



-- Postgres equivalent of MySQL's "ON UPDATE CURRENT_TIMESTAMP":
-- a trigger that stamps updated_at with the current time on every row update.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS '
BEGIN NEW.updated_at = CURRENT_TIMESTAMP; RETURN NEW; END;
' LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();