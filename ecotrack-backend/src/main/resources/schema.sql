CREATE TABLE IF NOT EXISTS emission_factors (
  emission_factor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category varchar(100) NOT NULL UNIQUE,
  unit varchar(50) NOT NULL,
  factor_value decimal NOT NULL,
  last_updated timestamp DEFAULT CURRENT_TIMESTAMP
);
 
CREATE TABLE IF NOT EXISTS carbon_entries (
  entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  emission_factor_id bigint NOT NULL,
  category varchar(100) NOT NULL,
  amount decimal NOT NULL,
  unit varchar(50) NOT NULL,
  carbon_emission decimal NOT NULL,
  activity_date date NOT NULL,
 
  CONSTRAINT fk_entry_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_entry_factor FOREIGN KEY (emission_factor_id) REFERENCES emission_factors(emission_factor_id)
);
 
