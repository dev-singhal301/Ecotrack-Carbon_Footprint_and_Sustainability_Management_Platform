CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

INSERT INTO roles (name)
VALUES
('ROLE_ADMIN'),
('ROLE_USER')
ON CONFLICT (name) DO NOTHING;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255),
    oauth_provider VARCHAR(30),
    oauth_id VARCHAR(255) UNIQUE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    reset_password_token VARCHAR(255) DEFAULT NULL,
    token_expiry_date DATETIME DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_role
        FOREIGN KEY (role_id)
        REFERENCES roles(id)
);

-- Milestone 2 — Person A scope: emission_factors, carbon_entries
CREATE TABLE IF NOT EXISTS emission_factors (
  emission_factor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category varchar(100) NOT NULL,
  unit varchar(50) NOT NULL,
  factor_value decimal NOT NULL,
  last_updated timestamp DEFAULT CURRENT_TIMESTAMP
);
 
CREATE TABLE IF NOT EXISTS carbon_entries (
  entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  emission_factor_id bigint NOT NULL,
  category varchar(100) NOT NULL,
  amount decimal NOT NULL,
  unit varchar(50) NOT NULL,
  carbon_emission decimal NOT NULL,
  activity_date date NOT NULL,
 
  CONSTRAINT fk_entry_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_entry_factor FOREIGN KEY (emission_factor_id) REFERENCES emission_factors(emission_factor_id)
);
 
