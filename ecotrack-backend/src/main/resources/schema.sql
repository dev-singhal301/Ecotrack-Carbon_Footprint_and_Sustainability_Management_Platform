-- 15. RECOMMENDATIONS TABLE
CREATE TABLE IF NOT EXISTS recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    category VARCHAR(100) NOT NULL,
    suggestion_text VARCHAR(500) NOT NULL,
    impact_estimate DECIMAL NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_recommendation_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,

    CONSTRAINT chk_recommendation_category
        CHECK (
            category IN (
                'TRANSPORTATION',
                'ELECTRICITY',
                'FOOD',
                'WASTE',
                'WATER',
                'FUEL'
            )
        ),

    CONSTRAINT chk_recommendation_impact_non_negative
        CHECK (impact_estimate >= 0)
);

-- Supports both RecommendationRepository query methods: findByUserId... and
-- deleteByUserId both filter on user_id first; impact_estimate included so
-- the ORDER BY impact_estimate DESC in findByUserIdOrderByImpactEstimateDesc
-- can be satisfied by the index instead of a separate sort.
CREATE INDEX IF NOT EXISTS idx_recommendations_user_impact
    ON recommendations(user_id, impact_estimate DESC);